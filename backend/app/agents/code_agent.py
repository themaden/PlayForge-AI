from backend.app.schemas import GameConcept

class CodeGenerationAgent:
    """Agent 2: Code Generation Agent 👨‍💻
    Synthesizes executable, standalone Phaser 3.80 scene logic based on game design specs.
    """

    def process(self, concept: GameConcept) -> str:
        if concept.mechanic == "Pull-The-Pin":
            return self._generate_pull_pin_code(concept)
        elif concept.mechanic == "Tile Blast":
            return self._generate_tile_blast_code(concept)
        else:
            return self._generate_match3_code(concept)

    def _generate_match3_code(self, concept: GameConcept) -> str:
        return f"""// Generated by PlayForge AI - Code Generation Agent
// Concept: {concept.title} ({concept.mechanic})

class PlayableScene extends Phaser.Scene {{
    constructor() {{
        super('PlayableScene');
        this.score = 0;
        this.targetScore = 300;
        this.timeLeft = {concept.duration_seconds};
        this.gameEnded = false;
    }}

    preload() {{
        // Assets preloaded procedurally
    }}

    create() {{
        const width = this.cameras.main.width;
        const height = this.cameras.main.height;

        // Background
        this.add.rectangle(width/2, height/2, width, height, 0x1e1b4b);

        // Header Title
        this.add.text(width/2, 40, "{concept.title}", {{
            font: 'bold 24px Arial',
            fill: '#ffffff'
        }}).setOrigin(0.5);

        // Subtitle goal
        this.add.text(width/2, 75, "{concept.primary_goal}", {{
            font: '14px Arial',
            wordWrap: {{ width: 300 }},
            fill: '#facc15'
        }}).setOrigin(0.5);

        // Match-3 Grid setup
        this.gridSize = 4;
        this.tileSize = 60;
        this.startOffsetX = (width - (this.gridSize * this.tileSize)) / 2 + 30;
        this.startOffsetY = 160;
        this.tiles = [];
        this.colors = [0xef4444, 0x3b82f6, 0x10b981, 0xf59e0b];

        this.createBoard();
        this.createTutorialHand();

        // Timer Event
        this.time.addEvent({{
            delay: 1000,
            callback: this.updateTimer,
            callbackScope: this,
            loop: true
        }});

        this.timerText = this.add.text(width - 20, 20, `⏳ ${{this.timeLeft}}s`, {{
            font: 'bold 18px Arial',
            fill: '#ffffff'
        }}).setOrigin(1, 0);
    }}

    createBoard() {{
        for (let row = 0; row < this.gridSize; row++) {{
            this.tiles[row] = [];
            for (let col = 0; col < this.gridSize; col++) {{
                const color = this.colors[(row + col) % this.colors.length];
                const x = this.startOffsetX + (col * this.tileSize);
                const y = this.startOffsetY + (row * this.tileSize);

                const tile = this.add.rectangle(x, y, 52, 52, color)
                    .setInteractive({{ useHandCursor: true }})
                    .setStrokeStyle(3, 0xffffff);

                tile.row = row;
                tile.col = col;

                tile.on('pointerdown', () => this.handleTileClick(tile));
                this.tiles[row][col] = tile;
            }}
        }}
    }}

    createTutorialHand() {{
        const targetTile = this.tiles[1][1];
        this.hand = this.add.text(targetTile.x + 15, targetTile.y + 15, '👆', {{
            font: '42px Arial'
        }}).setDepth(10);

        this.tweens.add({{
            targets: this.hand,
            scale: 1.2,
            duration: 500,
            yoyo: true,
            repeat: -1
        }});
    }}

    handleTileClick(tile) {{
        if (this.gameEnded || tile.consumed) return;
        tile.consumed = true;
        tile.disableInteractive();

        if (this.hand) {{
            this.hand.destroy();
            this.hand = null;
        }}

        // Pop effect
        this.tweens.add({{
            targets: tile,
            scaleX: 1.3,
            scaleY: 1.3,
            duration: 100,
            yoyo: true,
            onComplete: () => {{
                tile.setFillStyle(0xffffff);
                this.score += 100;
                this.checkWin();
            }}
        }});
    }}

    updateTimer() {{
        if (this.gameEnded) return;
        this.timeLeft--;
        this.timerText.setText(`⏳ ${{this.timeLeft}}s`);

        if (this.timeLeft <= 0) {{
            this.triggerCTA(false);
        }}
    }}

    checkWin() {{
        if (this.score >= this.targetScore) {{
            this.triggerCTA(true);
        }}
    }}

    triggerCTA(won) {{
        this.gameEnded = true;
        const width = this.cameras.main.width;
        const height = this.cameras.main.height;

        const overlay = this.add.rectangle(width/2, height/2, width, height, 0x000000, 0.85).setDepth(20);

        const bannerText = won ? '🎉 VICTORY! KING SAVED!' : '⚠️ TIME EXPIRED!';
        this.add.text(width/2, height/2 - 50, bannerText, {{
            font: 'bold 20px Arial',
            fill: won ? '#4ade80' : '#f87171'
        }}).setOrigin(0.5).setDepth(21);

        const ctaBtn = this.add.rectangle(width/2, height/2 + 40, 260, 60, 0x2563eb)
            .setInteractive({{ useHandCursor: true }})
            .setDepth(21);

        const ctaLabel = this.add.text(width/2, height/2 + 40, '{concept.cta_text}', {{
            font: 'bold 18px Arial',
            fill: '#ffffff'
        }}).setOrigin(0.5).setDepth(22);

        ctaBtn.on('pointerdown', () => {{
            if (window.mraid) window.mraid.open();
            else alert('Redirecting to App Store / Google Play!');
        }});
    }}
}}
"""

    def _generate_pull_pin_code(self, concept: GameConcept) -> str:
        raise NotImplementedError("Pull-the-pin is not implemented. Use the tap puzzle template.")

    def _generate_tile_blast_code(self, concept: GameConcept) -> str:
        raise NotImplementedError("Tile blast is not implemented. Use the tap puzzle template.")
